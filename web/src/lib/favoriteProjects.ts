/**
 * Избранные проекты человека — один срез для мобильной «Главной» и сайдбара.
 *
 * Отдельным чистым модулем, а не `.filter` на месте: до 30.09 сайдбар
 * показывал избранное в серверном порядке (`created_at desc`), а папки рядом —
 * по имени, и один человек на двух устройствах видел бы разный порядок одного
 * и того же набора. Для ручной подборки «что завёл раньше» ничего не значит.
 *
 * `lib/favorites.ts` — НЕ про проекты: там learn-избранное (материалы, курсы,
 * товары, новости) со своими ключами и ручками.
 */

import { type Project } from './projects'

/**
 * Только `is_favorite`, по имени с русской локалью — тот же компаратор, что у
 * проектов внутри папок (`groupProjectsByFolder`). Вход не мутируется: это
 * объект кэша TanStack, от его порядка зависит блок «Проекты» рядом.
 */
export function favoriteProjects(projects: Project[] | undefined): Project[] {
  return (projects ?? [])
    .filter((p) => p.is_favorite)
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name, 'ru'))
}
