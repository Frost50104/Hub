/**
 * «У вас старая сборка?» — ответ, не зависящий от Service Worker.
 *
 * Баннер и кнопка обновления раньше опирались только на состояние SW, а
 * именно оно в Safari подводит: замер в консоли живой вкладки владельца
 * (16.09) — `registration.update()` не резолвится ВООБЩЕ (15 002 мс без
 * ответа и без отказа), из-за чего кнопка висла, а событие о новом воркере до
 * баннера не доезжало.
 *
 * Сравнение версий свободно от этой болезни: `__APP_VERSION__` вшивается в
 * бандл при сборке из `web/public/version.json` (`vite.config.ts`), тот же
 * файл уезжает на сервер и отдаётся как `/version.json` с `no-store`. То есть
 * слева — версия ЗАГРУЖЕННОГО кода, справа — версия на сервере, и обе пишет
 * один `write_version` при деплое.
 *
 * Чистые функции, потому что vitest здесь без jsdom: ни компонент, ни хук не
 * покрыть, а правило покрыть обязано.
 */

/**
 * Показывать ли предложение обновиться.
 *
 * `server === null` — версию узнать не удалось (офлайн, 404 на дев-стенде):
 * молчим. Врать «есть обновление» на пустом месте хуже, чем промолчать, —
 * человек нажмёт и потеряет несохранённое.
 *
 * `dismissed` — версия, которую уже отложили кнопкой «Позже». Откладывается
 * КОНКРЕТНАЯ версия, а не факт: следующая новая обязана показаться снова,
 * иначе один отказ глушит баннер до перезагрузки вкладки.
 */
export function shouldOfferUpdate(
  loaded: string,
  server: string | null,
  dismissed: string | null = null,
): boolean {
  if (!server) return false
  if (server === loaded) return false
  return server !== dismissed
}
