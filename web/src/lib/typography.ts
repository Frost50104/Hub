/**
 * Неразрывные пробелы в метастроках — правило спеки редизайна, а не вкусовщина.
 *
 * На 360px почти каждая метастрока встаёт в две строки, и без связок вниз
 * уезжают одинокие хвосты: «1» и «240», «№» и «4187», «(0 из» и «1)».
 * Связка ставится ВНУТРИ одной смысловой единицы; между единицами перенос
 * по-прежнему нужен, поэтому метастрока собирается из отдельных фрагментов
 * (см. `MetaLine`), а не склеивается в один текстовый узел.
 */

export const NBSP = ' '

/** Единицы измерения, которые не должны отрываться от своего числа. */
const UNITS = [
  'мин',
  'сек',
  'ч',
  'дн[а-яё]*',
  'день',
  'нед[а-яё]*',
  'мес[а-яё]*',
  'год',
  'года',
  'лет',
  'байт',
  'КБ',
  'МБ',
  'ГБ',
  'шт',
  'стр[а-яё]*',
  'урок[а-яё]*',
  'вопрос[а-яё]*',
  'балл[а-яё]*',
  'попыт[а-яё]*',
  'курс[а-яё]*',
  'тест[а-яё]*',
  'из',
  '%',
  '₽',
].join('|')

const MONTHS =
  'январ[а-яё]*|феврал[а-яё]*|март[а-яё]*|апрел[а-яё]*|ма[йя][а-яё]*|июн[а-яё]*|июл[а-яё]*|август[а-яё]*|сентябр[а-яё]*|октябр[а-яё]*|ноябр[а-яё]*|декабр[а-яё]*'

/**
 * Ставит неразрывные пробелы внутри смысловых единиц одного фрагмента.
 * Фрагмент — уже отдельная единица метастроки, ломать его нельзя.
 */
export function nbsp(input: string): string {
  let out = input

  // Разряды числа: 1 240 → 1 240
  out = out.replace(/(\d)[ ](?=\d{3}(?!\d))/g, `$1${NBSP}`)

  // Число с единицей: 12 мин, 6,8 МБ, 2 ч, 0 из 1
  out = out.replace(new RegExp(`(\\d)[ ](?=(?:${UNITS})(?![а-яёА-ЯЁa-zA-Z]))`, 'g'), `$1${NBSP}`)

  // Дата с месяцем: 12 августа
  out = out.replace(new RegExp(`(\\d)[ ](?=(?:${MONTHS}))`, 'gi'), `$1${NBSP}`)

  // Номер со знаком: № 4187
  out = out.replace(/№[ ](?=\d)/g, `№${NBSP}`)

  // Дробь места: 7 / 62
  out = out.replace(/(\d)[ ]?\/[ ]?(?=\d)/g, `$1${NBSP}/${NBSP}`)

  // Содержимое коротких скобок: (0 из 1) — хвост «1)» не уезжает вниз один.
  out = out.replace(/\(([^()]{1,40})\)/g, (_m, inner: string) => `(${inner.replace(/ /g, NBSP)})`)

  return out
}

/**
 * Крупные числа в Unbounded: в дисплейной гарнитуре разряды широкие, и без
 * явного запрета «1 240» рвётся даже там, где места хватает.
 */
export const DISPLAY_NUMBER_CLASS = 'whitespace-nowrap tabular-nums'

/** «11 уроков», «4 теста» — единица всегда при своём числе. */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return `${n}${NBSP}${one}`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n}${NBSP}${few}`
  return `${n}${NBSP}${many}`
}

/** «~2 ч 10 мин» / «12 мин» — оценка времени чтения. */
export function formatMinutes(total: number): string {
  const minutes = Math.max(1, Math.round(total))
  if (minutes < 60) return `${minutes}${NBSP}мин`
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  return m === 0 ? `~${h}${NBSP}ч` : `~${h}${NBSP}ч${NBSP}${m}${NBSP}мин`
}
