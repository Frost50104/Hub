/**
 * Отбор и порядок проектов на экране «Архив».
 *
 * Отдельным чистым модулем, потому что оба решения тут легко «упростить» во
 * вред: серверный параметр называется `include_archived`, но он АДДИТИВНЫЙ —
 * отдаёт активные И архивные вперемешку, режима «только архив» у ручки нет.
 * Кто доверится имени параметра, покажет на экране архива живые проекты.
 */

import { type Project } from './projects'

/**
 * Архивные, новыми сверху.
 *
 * Порядок по `archived_at`, а не по `created_at` (как отдаёт сервер): вопрос к
 * архиву — «что я убрал последним», а не «что завёл раньше». Тай-брейкер по
 * имени обязателен: проекты, заархивированные скриптом в одну секунду, иначе
 * тасовались бы между загрузками — ровно та болезнь, что лечил тай-брейкер в
 * списке задач.
 */
export function archivedProjects(projects: Project[] | undefined): Project[] {
  return (projects ?? [])
    .filter((p) => p.archived_at !== null)
    .slice()
    .sort((a, b) => {
      const byDate = String(b.archived_at).localeCompare(String(a.archived_at))
      return byDate !== 0 ? byDate : a.name.localeCompare(b.name, 'ru')
    })
}
