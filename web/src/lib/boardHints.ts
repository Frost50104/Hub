import { plural } from './typography'

/**
 * Строка-объяснение над лентой доски.
 *
 * Правило «что написать над пустой доской» — из тех, что гниют в JSX молча:
 * условий три, и ошибка в любом даёт не падение, а ВРАНЬЁ на экране («задач
 * нет» проекту с 1 277 задачами). Поэтому оно живёт здесь и покрыто тестами.
 *
 * Колонки при этом видны ВСЕГДА, если они есть (решение владельца 26.08):
 * прятать свежесозданную колонку до первой разложенной задачи — значит ломать
 * ровно тот поток, ради которого проект теперь рождается пустым.
 */
export function boardHint(input: {
  /** Сколько колонок у проекта. */
  stages: number
  /** Задач верхнего уровня БЕЗ колонки — их на доске нет. */
  stageless: number
  /** Карточек на доске сейчас (после фильтров). */
  visible: number
}): string | null {
  const { stages, stageless, visible } = input

  if (stageless > 0) {
    const count = plural(stageless, 'задача', 'задачи', 'задач')
    // Согласование по числу: «1 задача … они в списке» — брак, который читают
    // как опечатку в продукте, а не как мелочь перевода.
    const one = stageless === 1
    return stages === 0
      ? `${count} пока без колонки — ${one ? 'она в списке' : 'они в списке'}. Создайте колонку, чтобы ${one ? 'положить её' : 'разложить их'} на доску.`
      : `${count} пока без колонки — ${one ? 'она в списке и появится' : 'они в списке и появятся'} на доске, когда выберете ${one ? 'ей' : 'им'} колонку.`
  }
  // Задач нет вовсе. Про колонки молчим: если их нет, на экране и так одна
  // кнопка «+ Колонка», и подпись к ней была бы шумом.
  if (visible === 0 && stages > 0) {
    return 'На доске пока нет задач — добавьте первую в любой колонке.'
  }
  return null
}

/**
 * Подзаголовок диалога удаления колонки: что именно предстоит решить.
 *
 * Отдельной функцией по той же причине, что и `boardHint`: цена ошибки —
 * согласование числа («1 задача … что с ними сделать») и молчание про
 * последнюю колонку, где переносить некуда.
 */
export function stageDeletePrompt(taskCount: number, hasOtherStages: boolean): string {
  if (taskCount === 0) return 'Колонка пуста — задачи переносить не нужно.'
  const count = plural(taskCount, 'задача', 'задачи', 'задач')
  const one = taskCount === 1
  if (hasOtherStages) {
    return `В колонке ${count} — выберите, что с ${one ? 'ней' : 'ними'} сделать.`
  }
  return (
    `Это последняя колонка. ${count} ${one ? 'останется' : 'останутся'} без колонки: ` +
    `${one ? 'она будет видна' : 'они будут видны'} в списке, в календаре и в поиске, но не на доске.`
  )
}
