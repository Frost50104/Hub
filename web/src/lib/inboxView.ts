/**
 * Тексты «Входящих», зависящие от состояния списка.
 *
 * Чистые и отдельно от JSX не для красоты: с дефолтом «Непрочитанные»
 * (31.08) обе строки стали ОСНОВНЫМ состоянием экрана, а не редким, и обе на
 * прежней ветке врали.
 */

import { plural } from './typography'

/**
 * Правая подпись над списком.
 *
 * `unread` обязан приходить из `/api/notifications/unread-count` — того же
 * источника, что бейдж в сайдбаре, — а НЕ из длины загруженного списка:
 * ручка отдаёт максимум 50 строк (`api/notifications.py`), и у человека со
 * 160 непрочитанными подпись говорила «50 непрочитанных».
 *
 * Дроби «N из M» здесь больше нет: M было числом ЗАГРУЖЕННЫХ уведомлений,
 * то есть тоже упиралось в лимит, а общего счётчика сервер не отдаёт. Одно
 * честное число лучше двух, из которых второе неверно.
 */
export function inboxCounter(unread: number): string {
  if (unread > 0) {
    return plural(unread, 'непрочитанное', 'непрочитанных', 'непрочитанных')
  }
  return 'Всё прочитано'
}

/**
 * Пустое состояние: «разобрано» и «не приходило» — разные новости.
 *
 * Текст окна непрочитанных нейтрален к тому, есть ли вообще уведомления: оно
 * же выпадает новичку, которому ещё ничего не приходило, а сколько всего их
 * в «Все», экран в этот момент не знает.
 */
export function inboxEmpty(unreadOnly: boolean): { title: string; body: string } {
  if (unreadOnly) {
    return {
      title: 'Всё прочитано',
      body: 'Ничего не ждёт ответа. Всё, что приходило, — на вкладке «Все».',
    }
  }
  return {
    title: 'Здесь пока тихо',
    body: 'Назначения, упоминания, комментарии и дедлайны попадут сюда.',
  }
}
