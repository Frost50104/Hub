/**
 * Корни кэша трекера — всё, что показывает задачи, их обсуждение и счётчики.
 *
 * Нужен там, где сервер поменял задачи, а угадать, что именно, нечем: переезд
 * задачи между проектами (меняет два проекта разом) и действия ассистента
 * (план или правка одной задачи прямо в ответе). Перечислять ключи по одному
 * в каждом таком месте нельзя: забытый корень оставит экран со старыми
 * данными, и выглядеть это будет как «действие не сработало», хотя сервер
 * отработал.
 *
 * Корни: списки и карточка (`tasks`), лента, комментарии и наблюдатели
 * (`task`), счётчики проектов, колонки, метки, кастом-поля, зависимости,
 * «Мои задачи», «Назначенные мной», статистика «Главной», хронология и
 * дашборд проекта (`stats`). Инвалидация неактивного ключа бесплатна — он
 * лишь помечается устаревшим и перечитается при монтировании.
 *
 * `tasks` задевает и деталь `['tasks','detail',id]`, а открытая карточка
 * пересоздаёт заголовок и описание на каждый новый объект задачи
 * (`TaskDetailDrawer`): звать это там, где карточка открыта и в ней могут
 * печатать, можно только осознанно. Ассистент живёт на своей странице, где
 * карточки нет; перенос запускается из диалога поверх карточки.
 */
export const TRACKER_ROOTS: readonly string[] = [
  'tasks',
  'task',
  'projects',
  'stages',
  'labels',
  'custom-fields',
  'dependencies',
  'me-tasks',
  'me-stats',
  'timeline',
  'me-assigned-by-me',
  'stats',
]

export function isTrackerQueryKey(key: readonly unknown[]): boolean {
  return TRACKER_ROOTS.includes(String(key[0]))
}
