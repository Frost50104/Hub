"""Две ступени прав проекта — и инвариант между ними.

Интеграционные тесты в CI не бегут, поэтому единственная автоматическая защита
этих констант — здесь. Ценность не в «проверить кортеж», а в том, что от них
зависят и гейты ручек, и флаги `can_edit`/`can_manage`, которые клиент рендерит
как «показать/спрятать контрол».
"""

from __future__ import annotations

from app.services.project_access import EDIT_ROLES, MANAGE_ROLES


def test_edit_tier_is_owner_and_editor() -> None:
    assert EDIT_ROLES == ("owner", "editor")


def test_manage_tier_is_owner_only() -> None:
    """Архив, удаление, участники, метки, кастом-поля — только владелец."""
    assert MANAGE_ROLES == ("owner",)


def test_manage_implies_edit() -> None:
    """«Умеешь управлять ⇒ умеешь править».

    На этом инварианте стоит гейт экрана «О проекте»: кнопка «Настройки
    проекта» показывается по ИЛИ четырёх прав, и если ступени разъедутся,
    экран деградирует в «настройки открылись, а внутри пусто» вместо того,
    чтобы спрятать кнопку у управляющего.
    """
    assert set(MANAGE_ROLES) <= set(EDIT_ROLES)
